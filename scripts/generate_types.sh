#!/bin/bash
# Generate Python types from Rust JSON schemas.
#
# Prerequisites:
#   pip install datamodel-code-generator
#
# Usage:
#   ./scripts/generate_types.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
SCHEMA_DIR="$ROOT_DIR/schemas"
OUTPUT_DIR="$ROOT_DIR/../sdktrader_py/sdktrader/generated"

echo "=== Step 1: Build and run schema exporter ==="
cd "$ROOT_DIR"
cargo run -p sdktrader-schema-export -- "$SCHEMA_DIR"

echo ""
echo "=== Step 2: Generate Pydantic models from JSON schemas ==="

# Check if datamodel-code-generator is installed
if ! command -v datamodel-codegen &> /dev/null; then
    echo "ERROR: datamodel-codegen not found."
    echo "Install it with: pip install datamodel-code-generator"
    exit 1
fi

mkdir -p "$OUTPUT_DIR"

# Generate a single Python file with all models
datamodel-codegen \
    --input "$SCHEMA_DIR" \
    --input-file-type jsonschema \
    --output "$OUTPUT_DIR/models.py" \
    --output-model-type pydantic_v2.BaseModel \
    --target-python-version 3.10 \
    --use-standard-collections \
    --use-union-operator \
    --field-constraints \
    --snake-case-field \
    --strip-default-none \
    --disable-timestamp

# Add header comment
TEMP_FILE=$(mktemp)
cat > "$TEMP_FILE" << 'PYEOF'
"""
Auto-generated Pydantic v2 models from sdktrader-core Rust types.

DO NOT EDIT MANUALLY — this file is regenerated by:
  ./scripts/generate_types.sh

Source of truth: sdktrader_rs/crates/sdktrader-core/src/models/
"""
PYEOF
cat "$OUTPUT_DIR/models.py" >> "$TEMP_FILE"
mv "$TEMP_FILE" "$OUTPUT_DIR/models.py"

# Create __init__.py if it doesn't exist
if [ ! -f "$OUTPUT_DIR/__init__.py" ]; then
    echo '"""Auto-generated types from Rust sdktrader-core."""' > "$OUTPUT_DIR/__init__.py"
    echo 'from .models import *  # noqa: F401,F403' >> "$OUTPUT_DIR/__init__.py"
fi

echo ""
echo "=== Done ==="
echo "Schemas: $SCHEMA_DIR/"
echo "Python:  $OUTPUT_DIR/models.py"
echo ""
echo "Run 'git diff' to see what changed."
